export function moneyLabel(value: string | null | undefined) {
  if (value == null) return "Montant inconnu";
  const [whole, decimal = "00"] = value.split(".");
  return (
    whole!.replace(/\B(?=(\d{3})+(?!\d))/g, "\u202f") + "," + decimal + " €"
  );
}
